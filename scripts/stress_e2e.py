def item3_get_feed(be: Backend, lib: str, manifest: dict):
    print("\n== Item 3: get_feed (days) ==", flush=True)
    ok, data, elapsed = be.request("get_feed", timeout=60, path=lib,
                                   view="days", limit=100000)
    expected = manifest["expected_feed_items"]
    total = count_feed(data) if ok else -1
    check("3", "get_feed ok", ok, str(data)[:200] if not ok else "")
    check("3", f"get_feed < 3s", elapsed < 3.0, f"elapsed={elapsed:.2f}s",
          threshold="< 3s", actual=f"{elapsed:.2f}s")
    check("3", f"feed returns every file exactly once ({expected})",
          total == expected, f"feed_items={total}", threshold=str(expected),
          actual=str(total))
    if ok and total == expected:
        got = feed_paths(data, STATE["lib_root"])
        want = set(manifest["files"].keys())
        dupes = len(got) - len(set(got))
        missing = want - set(got)
        extra = set(got) - want
        check("3", "feed set == manifest set, no double-count",
              not dupes and not missing and not extra,
              f"dupes={dupes}, missing={len(missing)}, extra={len(extra)}")
    STATE["feed_baseline"] = total


