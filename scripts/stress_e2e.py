def check(item, name, ok, detail="", threshold="", actual=""):
    (PASS if ok else FAIL).append(f"{item}:{name}")
    ROWS.append((item, name, threshold, actual, "PASS" if ok else "FAIL", detail))
    print(f"  [{'PASS' if ok else 'FAIL'}] [{item}] {name}"
          + (f" -- {detail}" if detail else ""), flush=True)


def info(item, name, value, note=""):
    ROWS.append((item, name, "-", value, "INFO", note))
    print(f"  [info] [{item}] {name}: {value}" + (f" ({note})" if note else ""),
          flush=True)


