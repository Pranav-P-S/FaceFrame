_PMC = None
_PTE32 = None


def _pmc_type():
    global _PMC
    if _PMC is None:
        import ctypes.wintypes as wt

        class PROCESS_MEMORY_COUNTERS(ctypes.Structure):
            _fields_ = [
                ("cb", wt.DWORD),
                ("PageFaultCount", wt.DWORD),
                ("PeakWorkingSetSize", ctypes.c_size_t),
                ("WorkingSetSize", ctypes.c_size_t),
                ("QuotaPeakPagedPoolUsage", ctypes.c_size_t),
                ("QuotaPagedPoolUsage", ctypes.c_size_t),
                ("QuotaPeakNonPagedPoolUsage", ctypes.c_size_t),
                ("QuotaNonPagedPoolUsage", ctypes.c_size_t),
                ("PagefileUsage", ctypes.c_size_t),
                ("PeakPagefileUsage", ctypes.c_size_t),
            ]
        _PMC = PROCESS_MEMORY_COUNTERS
    return _PMC


def _process_tree_snapshot():
    """pid -> (parent_pid, exe) for every process, via Toolhelp snapshot."""
    global _PTE32
    import ctypes.wintypes as wt

    if _PTE32 is not None:
        return _PTE32

    class PROCESSENTRY32W(ctypes.Structure):
        _fields_ = [
            ("dwSize", wt.DWORD),
            ("cntUsage", wt.DWORD),
            ("th32ProcessID", wt.DWORD),
            ("th32DefaultHeapID", ctypes.POINTER(wt.ULONG)),
            ("th32ModuleID", wt.DWORD),
            ("cntThreads", wt.DWORD),
            ("th32ParentProcessID", wt.DWORD),
            ("pcPriClassBase", ctypes.c_long),
            ("dwFlags", wt.DWORD),
            ("szExeFile", wt.WCHAR * 260),
        ]

    k32 = ctypes.WinDLL("kernel32", use_last_error=True)
    _PTE32 = (k32, PROCESSENTRY32W)
    return _PTE32


def _descendant_pids(root_pid: int) -> list[int]:
    k32, te32 = _process_tree_snapshot()
    TH32CS_SNAPPROCESS = 0x2
    snap = k32.CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0)
    if snap == -1:
        return [root_pid]
    parent_of = {}
    entry = te32()
    entry.dwSize = ctypes.sizeof(entry)
    ok = k32.Process32FirstW(snap, ctypes.byref(entry))
    while ok:
        parent_of[int(entry.th32ProcessID)] = int(entry.th32ParentProcessID)
        ok = k32.Process32NextW(snap, ctypes.byref(entry))
    k32.CloseHandle(snap)
    children: dict[int, list[int]] = {}
    for pid, ppid in parent_of.items():
        children.setdefault(ppid, []).append(pid)
    tree, stack = [root_pid], [root_pid]
    while stack:
        for child in children.get(stack.pop(), []):
            if child not in tree:
                tree.append(child)
                stack.append(child)
    return tree


def rss_bytes(pid: int) -> int | None:
    """Working set of a process TREE (venv python.exe is a stub that spawns
    the real interpreter as a child, so the root pid alone is meaningless).
    psutil when available, else the WinAPI."""
    try:
        import psutil
        total = 0
        for p in psutil.Process(pid).children(recursive=True) + [psutil.Process(pid)]:
            try:
                total += int(p.memory_info().rss)
            except Exception:
                pass
        return total or None
    except ImportError:
        pass
    except Exception:
        pass
    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    pmc_cls = _pmc_type()
    total = 0
    for tree_pid in _descendant_pids(int(pid)):
        pmc = pmc_cls()
        pmc.cb = ctypes.sizeof(pmc)
        handle = kernel32.OpenProcess(0x1000, False, tree_pid)
        if not handle:
            continue
        try:
            if kernel32.K32GetProcessMemoryInfo(handle, ctypes.byref(pmc), pmc.cb):
                total += int(pmc.WorkingSetSize)
        finally:
            kernel32.CloseHandle(handle)
    return total or None


def mb(nbytes):
    return "?" if nbytes is None else f"{nbytes / (1024 * 1024):.0f} MB"


def feed_paths(data, lib_root: str) -> list[str]:
    """Normalized item paths from feed/search payloads.

    get_feed and search return library-RELATIVE posix paths (views._base_items
    selects f.path directly); handle absolute payloads too, just in case."""
    out = []
    prefix = str(lib_root).rstrip("\\/") + os.sep
    lower_prefix = prefix.lower()
    for group in data.get("groups", []):
        for item in group.get("items", []):
            p = item["path"]
            if p.lower().startswith(lower_prefix):
                p = p[len(prefix):]
            out.append(p.replace("\\", "/"))
    return out


def abs_for(lib_root: str, rel: str) -> str:
    return os.path.join(lib_root, *rel.split("/"))


def count_feed(data) -> int:
    return sum(len(g.get("items", [])) for g in data.get("groups", []))


def run_scan(be: Backend, lib: str, timeout: float, provider="cpu"):
    """Start a scan and wait for scan_complete. Returns (ok, stats|error, wall)."""
    since = be.event_count()
    t0 = time.monotonic()
    ok, data, _ = be.request("scan", timeout=30, path=lib, provider=provider)
    if not ok:
        return False, data, time.monotonic() - t0
    evt = be.wait_event("scan_complete", timeout=timeout, since=since)
    wall = time.monotonic() - t0
    if evt is None:
        err = be.wait_event("scan_error", timeout=1, since=since)
        return False, (err or "no scan_complete event"), wall
    return True, evt, wall


def read_one_label(db_path: Path) -> str | None:
    """Read one indexed label term straight from the index (read-only)."""
    try:
        uri = db_path.as_uri() + "?mode=ro"
        conn = sqlite3.connect(uri, uri=True, timeout=5)
        try:
            row = conn.execute(
                "SELECT labels FROM media WHERE labels IS NOT NULL "
                "AND labels NOT IN ('[]', '') LIMIT 3"
            ).fetchone()
        finally:
            conn.close()
        if row:
            labels = json.loads(row[0])
            for term in labels:
                if term and term.strip():
                    return term.split(",")[0].split()[0].strip()
    except Exception as e:
        print(f"  [warn] label probe failed: {e}", flush=True)
    return None


