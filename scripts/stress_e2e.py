def setup(be: Backend, lib: str, manifest: dict):
    t0 = time.monotonic()
    ok, data, elapsed = be.request("ping", timeout=180)
    if not ok:
        print(f"FATAL: backend never answered ping: {data}", flush=True)
        sys.exit(1)
    startup = time.monotonic() - t0
    info("0", "backend startup -> first ping", f"{startup:.1f}s")
    ok, data, elapsed = be.request("open_library", timeout=60, path=lib)
    check("0", "open_library", ok, str(data)[:120])
    STATE.update({
        "lib": lib,
        "lib_root": str(Path(lib).resolve()),
        "manifest": manifest,
        "disk": {rel: meta["hash"] for rel, meta in manifest["files"].items()},
        "moved": {}, "staged": {}, "trash_hashes": [],
        "rss_startup": be.rss_bytes(),
    })


def item1_cold_scan(be: Backend, lib: str, manifest: dict):
    print("\n== Item 1: cold scan ==", flush=True)
    data_dir = Path(lib) / ".faceframe"
    if data_dir.exists():
        shutil.rmtree(data_dir)
    ok, evt, wall = run_scan(be, lib, timeout=float(STATE["cold_timeout"]))
    if not ok:
        check("1", "cold scan completes", False, str(evt)[:300])
        return
    stats = evt
    files = stats.get("files_total", 0)
    throughput = files / wall if wall > 0 else 0
    check("1", "cold scan completes", True)
    check("1", f"cold scan <= {STATE['cold_timeout']}s", wall <= STATE["cold_timeout"],
          f"wall={wall:.0f}s, backend_elapsed={stats.get('elapsed')}s",
          threshold=f"<= {STATE['cold_timeout']}s", actual=f"{wall:.0f}s")
    info("1", "cold scan files/s", f"{throughput:.1f}",
         f"{files} files, decoded={stats.get('decoded')}, "
         f"dedup_hits={stats.get('dedup_hits')}, videos={stats.get('videos')}, "
         f"faces={stats.get('faces')}, missing_now={stats.get('missing_now')}")
    check("1", "all files discovered", files == len(manifest["files"]),
          f"scan={files}, manifest={len(manifest['files'])}")
    STATE["rss_after_cold"] = be.rss_bytes()
    info("1", "backend working set after cold scan", mb(STATE["rss_after_cold"]))


