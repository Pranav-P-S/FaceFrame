    info("4", "backend working set after 50 get_feed", mb(rss_after),
         f"growth vs post-scan: {mb(growth) if growth >= 0 else '-' + mb(-growth)}")
    check("4", "RSS growth over 50 feeds < 500 MB", growth < 500 * 1024 * 1024,
          f"growth={mb(growth)}", threshold="< 500 MB", actual=mb(growth))


