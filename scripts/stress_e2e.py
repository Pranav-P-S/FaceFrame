def print_table():
    print("\n" + "=" * 100, flush=True)
    print(f"{'item':<5} {'check':<46} {'threshold':<12} {'actual':<12} {'verdict':<7} note",
          flush=True)
    print("-" * 100, flush=True)
    for item, name, threshold, actual, verdict, note in ROWS:
        line = f"{item:<5} {name[:46]:<46} {threshold:<12} {actual:<12} {verdict:<7}"
        if note:
            line += f" {note}"
        print(line, flush=True)
    print("=" * 100, flush=True)
    print(f"\nPASS: {len(PASS)}  FAIL: {len(FAIL)}", flush=True)
    if FAIL:
        print("Failed checks:", flush=True)
        for f in FAIL:
            print(f"  - {f}", flush=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lib", default=str(ROOT / "test-data" / "stress-library-3000"))
    ap.add_argument("--cold-timeout", type=int, default=1200,
                    help="cold scan threshold/timeout in seconds (default 1200)")
    ap.add_argument("--items", default="all",
                    help="comma list e.g. 1,2,3,13 (default: all)")
    args = ap.parse_args()

    lib = str(Path(args.lib).resolve())
    if (Path(lib) / ".faceframe").exists():
        print(
            "Refusing to run: the library already carries a .faceframe index "
            "from an earlier run and these scenarios MUTATE the library "
            "(moves, deletes, trash), which fakes failures. Regenerate it "
            "first:  python scripts/stress_library.py --out <lib> --force",
            flush=True,
        )
        return 2
    manifest_path = Path(lib) / "stress_manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    STATE["cold_timeout"] = args.cold_timeout

    LOG_DIR.mkdir(parents=True, exist_ok=True)
    log_path = LOG_DIR / f"backend_{Path(lib).name}.log"
    results_path = LOG_DIR / f"results_{Path(lib).name}.json"

    which = None if args.items == "all" else {s.strip() for s in args.items.split(",")}

    print(f"Library: {lib}", flush=True)
    print(f"Expected feed items: {manifest['expected_feed_items']} "
          f"({manifest['photos_total']} photos incl {manifest['duplicates']} dup "
          f"copies + {manifest['videos']} videos)", flush=True)
    print(f"Backend log: {log_path}", flush=True)

    be = Backend(log_path)
    try:
        setup(be, lib, manifest)
        if which is None or "1" in which:
            item1_cold_scan(be, lib, manifest)
        if which is None or "2" in which:
            item2_warm_rescan(be, lib, manifest)
        if which is None or "3" in which:
            item3_get_feed(be, lib, manifest)
        if which is None or "4" in which:
            item4_feed_repeats_and_memory(be, lib, manifest)
        if which is None or "5" in which:
            setup_favorites_and_label(be, lib, manifest)
            item5_search(be, lib, manifest)
        if which is None or "6" in which:
            item6_duplicates(be, lib, manifest)
        if which is None or "7" in which:
            item7_album(be, lib, manifest)
        if which is None or "8" in which:
            item8_move_200(be, lib, manifest)
        if which is None or "9" in which:
            item9_delete_300(be, lib, manifest)
        if which is None or "10" in which:
            item10_restore_100(be, lib, manifest)
        if which is None or "11" in which:
            item11_trash_bulk(be, lib, manifest)
        if which is None or "13" in which:
            item13_concurrency(be, lib, manifest)
    finally:
        payload = {
            "lib": lib,
            "finished": time.strftime("%Y-%m-%d %H:%M:%S"),
            "rows": [
                {"item": i, "check": n, "threshold": t, "actual": a,
                 "verdict": v, "note": d}
                for i, n, t, a, v, d in ROWS
            ],
            "pass_count": len(PASS),
            "fail_count": len(FAIL),
            "rss": {
                "startup": STATE.get("rss_startup"),
                "after_cold_scan": STATE.get("rss_after_cold"),
                "final": STATE.get("rss_final"),
            },
        }
        results_path.write_text(json.dumps(payload, indent=1), encoding="utf-8")
        print_table()
        be.close()
        print(f"\nResults JSON: {results_path}", flush=True)
    return 1 if FAIL else 0


if __name__ == "__main__":
    sys.exit(main())
