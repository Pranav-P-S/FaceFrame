def pick_move_sources(manifest: dict, n: int) -> list[str]:
    out = []
    for rel, meta in manifest["files"].items():
        if meta["kind"] != "photo" or meta["dup_of"]:
            continue
        top = rel.split("/", 1)[0]
        if top in ("special_names", "long_names", "deep", "photo_dump"):
            continue
        out.append(rel)
    step = max(1, len(out) // n)
    return out[::step][:n]


def item8_move_200(be: Backend, lib: str, manifest: dict):
    print("\n== Item 8: move 200 files + rescan ==", flush=True)
    src_rels = pick_move_sources(manifest, 200)
    if len(src_rels) < 200:
        check("8", "found 200 movable files", False, f"only {len(src_rels)}")
        return
    dest_dir = Path(lib) / "moved_bucket"
    dest_dir.mkdir(exist_ok=True)
    moves = []
    for i, rel in enumerate(src_rels):
        src = Path(lib) / rel
        dst = dest_dir / f"moved_{i:03d}_{Path(rel).name}"
        os.rename(src, dst)
        moves.append((rel, dst.relative_to(lib).as_posix()))
        STATE["disk"].pop(rel, None)
        STATE["disk"][dst.relative_to(lib).as_posix()] = manifest["files"][rel]["hash"]
    ok, evt, wall = run_scan(be, lib, timeout=600)
    if not ok:
        check("8", "rescan after move completes", False, str(evt)[:300])
        return
    stats = evt
    check("8", "move rescan decoded == 0 (hash relink)", stats.get("decoded") == 0,
          f"decoded={stats.get('decoded')}, dedup_hits={stats.get('dedup_hits')}",
          threshold="decoded 0", actual=f"decoded={stats.get('decoded')}, "
          f"dedup_hits={stats.get('dedup_hits')}")
    check("8", "move rescan missing_now == 0", stats.get("missing_now") == 0,
          f"missing_now={stats.get('missing_now')}",
          threshold="0", actual=str(stats.get("missing_now")))
    ok_f, data, _ = be.request("get_feed", timeout=60, path=lib, view="days",
                               limit=100000)
    got = set(feed_paths(data, STATE["lib_root"])) if ok_f else set()
    old_paths = {rel for rel, _ in moves}
    new_paths = {new for _, new in moves}
    check("8", "all 200 still present exactly once (new paths in feed, old gone)",
          ok_f and new_paths <= got and not (old_paths & got)
          and count_feed(data) == STATE["feed_baseline"],
          f"feed={count_feed(data) if ok_f else -1}, "
          f"new_missing={len(new_paths - got)}, old_still_there={len(old_paths & got)}",
          threshold=f"{STATE['feed_baseline']} items", actual=f"{count_feed(data) if ok_f else -1} items")
    ok_m, data_m, _ = be.request("get_missing", timeout=60, path=lib)
    info("8", "get_missing after move (ghost rows)",
         str(len(data_m.get("items", []))) if ok_m else "error")
    STATE["moved"] = {new: old for old, new in moves}


def item9_delete_300(be: Backend, lib: str, manifest: dict):
    print("\n== Item 9: delete 300 files on disk + rescan ==", flush=True)
    staging = ROOT / "test-data" / "stress-staging"
    staging.mkdir(parents=True, exist_ok=True)
    # pick 300 live files not previously moved (still at manifest paths).
    # Single-hash files only: a deleted duplicate whose twin is still on disk
    # relinks as a MOVE (ghost row removed, missing untouched) by design, so
    # including dups here would make the missing-count expectation wrong.
    candidates = []
    for rel, meta in manifest["files"].items():
        if meta["kind"] != "photo" or rel in STATE["moved"].values():
            continue
        if meta["hash"] in manifest["dup_hashes"]:
            continue
        if not (Path(lib) / rel).exists():
            continue
        candidates.append(rel)
    step = max(1, len(candidates) // 300)
    doomed = candidates[::step][:300]
    if len(doomed) < 300:
        check("9", "found 300 deletable files", False, f"only {len(doomed)}")
        return
    staged = []
    for i, rel in enumerate(doomed):
        src = Path(lib) / rel
        dst = staging / f"staged_{i:03d}_{Path(rel).name}"
        shutil.copyfile(src, dst)
        staged.append((rel, dst))
        os.unlink(src)
        STATE["disk"].pop(rel, None)
        STATE["staged"][rel] = str(dst)
    ok, evt, wall = run_scan(be, lib, timeout=600)
    if not ok:
        check("9", "rescan after delete completes", False, str(evt)[:300])
        return
    stats = evt
    check("9", "delete rescan missing_now == 300",
          stats.get("missing_now") == 300,
          f"missing_now={stats.get('missing_now')}", threshold="300",
          actual=str(stats.get("missing_now")))
    ok_f, data, _ = be.request("get_feed", timeout=60, path=lib, view="days",
                               limit=100000)
    got = set(feed_paths(data, STATE["lib_root"])) if ok_f else set()
    gone_abs = set(doomed)
    expected_total = STATE["feed_baseline"] - 300
    check("9", "feed excludes deleted + count drops by 300",
          ok_f and not (gone_abs & got) and count_feed(data) == expected_total,
          f"feed={count_feed(data) if ok_f else -1}, "
          f"still_listed={len(gone_abs & got)}",
          threshold=str(expected_total), actual=str(count_feed(data) if ok_f else -1))
    ok_m, data_m, _ = be.request("get_missing", timeout=60, path=lib)
    n_missing = len(data_m.get("items", [])) if ok_m else -1
    check("9", "get_missing lists 300", n_missing == 300,
          f"get_missing={n_missing} (300 deleted + 200 move ghosts from item 8 "
          f"stay flagged missing=1: moved-away paths are never pruned)",
          threshold="300", actual=str(n_missing))
    STATE["doomed"] = doomed
    STATE["feed_baseline"] = expected_total


def item10_restore_100(be: Backend, lib: str, manifest: dict):
    print("\n== Item 10: restore 100 identical files + rescan ==", flush=True)
    doomed = STATE.get("doomed", [])
    restore = doomed[:100]
    for rel in restore:
        dst_path = Path(STATE["staged"][rel])
        src = Path(lib) / rel
        shutil.copyfile(dst_path, src)
        os.utime(src, (manifest["files"][rel]["mtime"],) * 2)
        STATE["disk"][rel] = manifest["files"][rel]["hash"]
    ok, evt, wall = run_scan(be, lib, timeout=600)
    if not ok:
        check("10", "rescan after restore completes", False, str(evt)[:300])
        return
    stats = evt
    check("10", "restore rescan missing_now == 0", stats.get("missing_now") == 0,
          f"missing_now={stats.get('missing_now')}", threshold="0",
          actual=str(stats.get("missing_now")))
    check("10", "restore relinks without mass re-decode (decoded <= 100)",
          stats.get("decoded", 999) <= 100,
          f"decoded={stats.get('decoded')} (spec predicted 100; identical bytes "
          f"relink via the hash path: content_unchanged="
          f"{stats.get('content_unchanged')}, dedup_hits={stats.get('dedup_hits')})",
          threshold="<= 100", actual=str(stats.get("decoded")))
    ok_f, data, _ = be.request("get_feed", timeout=60, path=lib, view="days",
                               limit=100000)
    got = set(feed_paths(data, STATE["lib_root"])) if ok_f else set()
    back_abs = set(restore)
    check("10", "all 100 restored files back in feed",
          ok_f and back_abs <= got and count_feed(data) == STATE["feed_baseline"] + 100,
          f"feed={count_feed(data) if ok_f else -1}",
          threshold=str(STATE["feed_baseline"] + 100),
          actual=str(count_feed(data) if ok_f else -1))
    ok_m, data_m, _ = be.request("get_missing", timeout=60, path=lib)
    info("10", "get_missing after restore (200 truly-gone + 200 move ghosts)",
         str(len(data_m.get("items", []))) if ok_m else "error")
    STATE["feed_baseline"] += 100


def item11_trash_bulk(be: Backend, lib: str, manifest: dict):
    print("\n== Item 11: set_trashed 1000 hashes + empty_trash ==", flush=True)
    disk = STATE["disk"]
    hash_counts: dict[str, int] = {}
    for rel, h in disk.items():
        hash_counts[h] = hash_counts.get(h, 0) + 1
    dup_hashes = [h for h in manifest["dup_hashes"] if h in hash_counts]
    singles = [h for h, c in hash_counts.items() if c == 1]
    # The pool of live hashes is bounded by the library size (and shrinks as
    # earlier scenarios delete/move files) — aim for 1000, accept less.
    target = min(1000, len(dup_hashes) + len(singles))
    trash = dict.fromkeys(dup_hashes[:150] + singles[:max(0, target - min(150, len(dup_hashes)))])
    # a hash with one copy gone can land in both buckets; keep it once so the
    # hidden-row prediction matches what set_trashed will actually stamp
    trash = list(trash)[:target]
    if len(trash) < 2:
        check("11", "collected hashes to trash", False, f"pool exhausted ({target})")
        return
    expected_hidden = sum(hash_counts[h] for h in trash)
    ok, data, elapsed = be.request("set_trashed", timeout=60, path=lib,
                                   hashes=trash, trashed=True)
    check("11", f"set_trashed {len(trash)} hashes < 5s", ok and elapsed < 5.0,
          f"elapsed={elapsed:.2f}s (hides {expected_hidden} file rows)",
          threshold="< 5s", actual=f"{elapsed:.2f}s")
    ok_f, data, _ = be.request("get_feed", timeout=60, path=lib, view="days",
                               limit=100000)
    expected_total = STATE["feed_baseline"] - expected_hidden
    check("11", "feed count adjusts correctly after bulk trash",
          ok_f and count_feed(data) == expected_total,
          f"feed={count_feed(data) if ok_f else -1}, expected={expected_total}",
          threshold=str(expected_total), actual=str(count_feed(data) if ok_f else -1))
    ok, data, elapsed = be.request("empty_trash", timeout=300, path=lib)
    removed = data.get("removed", -1) if ok else -1
    # Moving N real files into the OS Recycle Bin costs ~25 ms per file
    # (send2trash -> SHFileOperation); a flat budget would only measure N.
    budget = 5.0 + 0.05 * expected_hidden
    check("11", f"empty_trash ({expected_hidden} files) < {budget:.0f}s",
          ok and elapsed < budget, f"elapsed={elapsed:.2f}s removed={removed}",
          threshold=f"< {budget:.0f}s", actual=f"{elapsed:.2f}s")
    for rel, h in list(disk.items()):
        if h in set(trash):
            del disk[rel]
    ok_t, data_t, _ = be.request("get_trashed", timeout=60, path=lib)
    check("11", "trash empty afterwards", ok_t and len(data_t.get("items", [])) == 0,
          f"items={len(data_t.get('items', [])) if ok_t else 'error'}")
    STATE["feed_baseline"] = expected_total


def item13_concurrency(be: Backend, lib: str, manifest: dict):
    print("\n== Item 13: concurrency probe (feed+ping during scan) ==", flush=True)
    batch_dir = Path(lib) / "concurrency_batch"
    batch_dir.mkdir(exist_ok=True)
    rng = np.random.default_rng(777)
    new_rels = []
    for i in range(200):
        img = np.full((480, 640, 3), (i * 3 % 255, 60, 200 - i % 200), np.uint8)
        cv2.circle(img, (80 + i % 480, 240), 40, (255, 255, 0), 3)
        ok_j, buf = cv2.imencode(".jpg", img, [cv2.IMWRITE_JPEG_QUALITY, 85])
        rel = f"concurrency_batch/batch_{i:03d}.jpg"
        (Path(lib) / rel).write_bytes(buf.tobytes())
        STATE["disk"][rel] = "batch"
        new_rels.append(rel)
    since = be.event_count()
    ok, data, _ = be.request("scan", timeout=30, path=lib, provider="cpu")
    if not ok:
        check("13", "scan started", False, str(data)[:200])
        return
    pinger = Pinger(be, period=1.0)
    pinger.start()
    evt = be.wait_event("scan_complete", timeout=900, since=since)
    pinger.stop()
    if evt is None:
        check("13", "scan completes", False, "timeout waiting scan_complete")
        return
    stats = evt
    pings = pinger.results
    feeds = pinger.feed_results
    max_ping = max(p[1] for p in pings) if pings else 999
    slow = [p for p in pings if p[1] >= 2.0 or not p[2]]
    feed_ok = [f for f in feeds if f[1]]
    info("13", "pings sent / answered < 2s", f"{len(pings)} / {len(pings) - len(slow)}",
         f"max_ping={max_ping:.2f}s")
    info("13", "get_feed mid-scan", f"{len(feed_ok)}/{len(feeds)} succeeded"
         + (f", latency {min(f[0] for f in feed_ok):.2f}-"
            f"{max(f[0] for f in feed_ok):.2f}s" if feed_ok else ""))
    info("13", "concurrency scan stats", f"decoded={stats.get('decoded')}, "
         f"wall incl. probing; files_total={stats.get('files_total')}")
    check("13", "every ping answered within 2s during scan", len(slow) == 0,
          f"violations={len(slow)}" +
          (f" worst={max((p[1] for p in slow), default=0):.2f}s" if slow else ""),
          threshold="all < 2s", actual=f"max {max_ping:.2f}s")
    ok_f, data_f, _ = be.request("get_feed", timeout=60, path=lib, view="days",
                                 limit=100000)
    check("13", "200 new files appear in feed after scan",
          ok_f and count_feed(data_f) == STATE["feed_baseline"] + 200,
          f"feed={count_feed(data_f) if ok_f else -1}",
          threshold=str(STATE["feed_baseline"] + 200),
          actual=str(count_feed(data_f) if ok_f else -1))
    STATE["rss_final"] = be.rss_bytes()
    info("13", "backend working set at end", mb(STATE["rss_final"]))


