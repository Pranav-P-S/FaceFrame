class Backend:
    def __init__(self, stderr_path: Path):
        self.proc = subprocess.Popen(
            [PYTHON, "-u", str(BACKEND)],
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=open(stderr_path, "w", encoding="utf-8", errors="replace"),
            text=True,
            encoding="utf-8",
            cwd=str(ROOT),
        )
        self.events = []           # every event line, in order
        self.event_times = []      # monotonic time per event
        self._responses = {}
        self._waiters = {}
        self._id = 0
        self._cursor = 0           # wait_for_event cursor
        self._lock = threading.Lock()
        self._reader = threading.Thread(target=self._read, daemon=True)
        self._reader.start()

    def _read(self):
        for line in self.proc.stdout:
            line = line.strip()
            if not line:
                continue
            try:
                msg = json.loads(line)
            except json.JSONDecodeError:
                continue
            with self._lock:
                if "id" in msg:
                    self._responses[msg["id"]] = msg
                    waiter = self._waiters.pop(msg["id"], None)
                    if waiter:
                        waiter.set()
                elif "event" in msg:
                    self.events.append(msg)
                    self.event_times.append(time.monotonic())

    def request(self, action, timeout=120, **params):
        """Returns (ok, data_or_error, elapsed_seconds)."""
        with self._lock:
            self._id += 1
            req_id = self._id
            self._waiters[req_id] = threading.Event()
        line = json.dumps({"id": req_id, "action": action, **params})
        t0 = time.monotonic()
        try:
            self.proc.stdin.write(line + "\n")
            self.proc.stdin.flush()
        except (BrokenPipeError, ValueError) as e:
            return False, f"stdin closed: {e}", 0.0
        if not self._waiters[req_id].wait(timeout):
            return False, f"timeout after {timeout}s", time.monotonic() - t0
        elapsed = time.monotonic() - t0
        msg = self._responses.get(req_id, {})
        if msg.get("ok"):
            return True, msg.get("data", {}), elapsed
        return False, msg.get("error", "unknown error"), elapsed

    def wait_event(self, name, timeout, since=None):
        """Blocks for the next event `name`; returns it or None on timeout."""
        deadline = time.time() + timeout
        start = self._cursor if since is None else since
        while time.time() < deadline:
            with self._lock:
                idx = max(start, 0)
                while idx < len(self.events):
                    if self.events[idx]["event"] == name:
                        self._cursor = idx + 1
                        return self.events[idx]
                    idx += 1
                self._cursor = idx
            time.sleep(0.05)
        return None

    def events_since(self, since):
        with self._lock:
            return list(self.events[since:])

    def event_count(self):
        with self._lock:
            return len(self.events)

    def rss_bytes(self):
        return rss_bytes(self.proc.pid)

    def close(self):
        try:
            self.proc.stdin.close()
        except Exception:
            pass
        try:
            self.proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            self.proc.kill()


class Pinger(threading.Thread):
    """Background ping loop used while a scan runs (item 13)."""

    def __init__(self, backend: Backend, period: float = 1.0):
        super().__init__(daemon=True)
        self.backend = backend
        self.period = period
        self.results = []  # (t, elapsed, ok)
        self.feed_results = []  # (elapsed, ok, count)
        self._halt = threading.Event()

    def run(self):
        while not self._halt.is_set():
            t = time.monotonic()
            ok, data, elapsed = self.backend.request("ping", timeout=10)
            self.results.append((t, elapsed, ok))
            ok_f, data_f, elapsed_f = self.backend.request(
                "get_feed", timeout=15, path=STATE["lib"], view="days",
                limit=100000)
            n = sum(len(g.get("items", [])) for g in data_f.get("groups", [])) \
                if ok_f else -1
            self.feed_results.append((elapsed_f, ok_f, n))
            self._halt.wait(max(0.0, self.period - (time.monotonic() - t)))

    def stop(self):
        self._halt.set()
        self.join(timeout=20)


